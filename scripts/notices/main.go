// Command notices writes THIRD_PARTY_NOTICES.txt: the licenses of everything linked into
// dnstt-cli, for both release platforms at once.
//
//	go run ./scripts/notices -dest .
//
// One file, not one per platform: the program is one binary built from one module, and
// the list is the union of what links into it on either platform, so a Windows-only
// dependency is not missed. The list comes from
//
//	go list -deps -json ./cmd/dnstt-cli     (GOOS=linux and GOOS=windows, GOARCH=amd64,
//	                                        CGO_ENABLED=0)
//
// with replace from go.mod applied — what really links into the binary. `go list -m all`
// would not do: it brings test-only modules and modules whose code never gets into the
// binary.
//
// The order is: the Go runtime and standard library first, their LICENSE and PATENTS
// taken from GOROOT; then every module, sorted by path and version; then the program's
// own parts — the shell, MIT (LICENSE in the repository root), and the dnstt core, public
// domain, CC0 (core/COPYING).
//
// The file is committed and regenerated byte for byte. There is no toolchain version and
// no path of the build machine in it, so it does not change when Go or the machine
// changes; the release workflow checks that the committed copy is current. Line endings
// are LF.
//
// No license text is invented: a module without a license file in its directory, or with
// a license text whose kind is not recognised, stops the command; such a module has to be
// looked at by a person, not silenced.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/FreedomCats/dnstt-cli/scripts/internal/script"
)

const (
	self = "notices"
	// mainModule is the program's own module: its packages are not third-party modules,
	// and its parts are the last sections of the file.
	mainModule = "github.com/FreedomCats/dnstt-cli"
	outName    = "THIRD_PARTY_NOTICES.txt"
)

// platforms are the release platforms. The module list is the union over them.
var platforms = []string{"linux/amd64", "windows/amd64"}

func main() {
	dest := flag.String("dest", "", "directory to write "+outName+" to (required)")
	flag.Parse()
	if *dest == "" || flag.NArg() > 0 {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*dest); err != nil {
		script.Fail(self, err)
	}
}

func run(dest string) error {
	root, err := script.Root()
	if err != nil {
		return err
	}
	goroot, err := goEnv("GOROOT")
	if err != nil {
		return err
	}
	mods, err := listModules(root)
	if err != nil {
		return err
	}
	sections, err := collect(mods, goroot)
	if err != nil {
		return err
	}
	own, err := ownSections(root)
	if err != nil {
		return err
	}
	text := render(append(sections, own...))
	if err := os.MkdirAll(dest, 0o755); err != nil {
		return err
	}
	out := filepath.Join(dest, outName)
	if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
		return err
	}
	script.Sayf("%s: %d components", out, len(sections)+len(own))
	return nil
}

// goEnv is one value of `go env`. Only GOROOT is read: the toolchain version must not get
// into the committed file, and the license files are what is needed from the toolchain.
func goEnv(name string) (string, error) {
	out, err := exec.Command("go", "env", name).Output()
	if err != nil {
		return "", fmt.Errorf("go env %s: %w", name, err)
	}
	value := strings.TrimSpace(strings.ReplaceAll(string(out), "\r\n", "\n"))
	if value == "" {
		return "", fmt.Errorf("go env %s: empty output", name)
	}
	return value, nil
}

// --- modules ---------------------------------------------------------------

// module is a Go module that links into the program.
type module struct {
	Path    string
	Version string
	Dir     string
	// Main marks the program's own module in go list output.
	Main    bool
	Replace *module
}

// title is the module in the file: path and version, as in go.mod.
func (m module) title() string {
	return strings.TrimSpace(m.Path + " " + m.Version)
}

// listModules is the union of the modules that link into ./cmd/dnstt-cli on the release
// platforms.
func listModules(root string) ([]module, error) {
	var lists [][]module
	for _, platform := range platforms {
		goos, goarch, _ := strings.Cut(platform, "/")
		mods, err := listPlatform(root, goos, goarch)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", platform, err)
		}
		lists = append(lists, mods)
	}
	return merge(lists...), nil
}

// merge is the union of module lists: each module once, sorted by path, then by version.
// Two versions of one module stay both: both link into the binary, and both need a
// license in the file.
func merge(lists ...[]module) []module {
	seen := map[string]module{}
	var mods []module
	for _, list := range lists {
		for _, m := range list {
			key := m.Path + "@" + m.Version
			if _, ok := seen[key]; ok {
				continue
			}
			seen[key] = m
			mods = append(mods, m)
		}
	}
	slices.SortFunc(mods, func(a, b module) int {
		if c := strings.Compare(strings.ToLower(a.Path), strings.ToLower(b.Path)); c != 0 {
			return c
		}
		if c := strings.Compare(a.Path, b.Path); c != 0 {
			return c
		}
		return strings.Compare(a.Version, b.Version)
	})
	return mods
}

// listPlatform is the modules that link into ./cmd/dnstt-cli for goos/goarch. The main
// module and the standard library are left out: they are not third-party.
func listPlatform(root, goos, goarch string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-json=Standard,Module", "./cmd/dnstt-cli")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	return parseModules(out)
}

// parseModules reads the stream of `go list -deps -json`: one JSON object per package.
// A module replaced in go.mod is listed as the replacement — that is the code that links
// into the binary.
func parseModules(listJSON []byte) ([]module, error) {
	var mods []module
	dec := json.NewDecoder(bytes.NewReader(listJSON))
	for {
		var p struct {
			Standard bool
			Module   *module
		}
		switch err := dec.Decode(&p); {
		case err == io.EOF:
			return mods, nil
		case err != nil:
			return nil, fmt.Errorf("parsing go list: %w", err)
		}
		m := p.Module
		if p.Standard || m == nil || m.Main || m.Path == mainModule {
			continue
		}
		if m.Replace != nil {
			m = m.Replace
		}
		mods = append(mods, *m)
	}
}

// --- licenses --------------------------------------------------------------

// section is one component of the file.
type section struct {
	Title string
	Kind  string
	Note  string
	Files []licenseText
}

// licenseText is one license file: only the name, no directory of the machine.
type licenseText struct {
	Name string
	Text string
}

var (
	reLicenseFile = regexp.MustCompile(`(?i)^(?:LICEN[CS]E|COPYING|COPYRIGHT|UNLICENSE|PATENTS|NOTICE)`)
	reMainFile    = regexp.MustCompile(`(?i)^(?:LICEN[CS]E|COPYING|UNLICENSE)`)
	reSpace       = regexp.MustCompile(`\s+`)
	reISC         = regexp.MustCompile(`Permission to use, copy, modify, and(?:/or)? distribute`)
)

// licenseFiles are the license files in the root of dir, the main ones (LICENSE, COPYING)
// first: the kind of a module's license is read from the first. The case of a name does
// not matter (LICENSE.md, license-mit), but source files that start the same way
// (license.go) are not licenses.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var main, rest []string
	for _, e := range entries {
		name := e.Name()
		if !e.Type().IsRegular() || !reLicenseFile.MatchString(name) || strings.EqualFold(filepath.Ext(name), ".go") {
			continue
		}
		if reMainFile.MatchString(name) {
			main = append(main, filepath.Join(dir, name))
		} else {
			rest = append(rest, filepath.Join(dir, name))
		}
	}
	return append(main, rest...), nil
}

// classify is the kind of a license by its text, or "" if the kind is not recognised.
//
// A file may hold several license texts: a module whose parts are under different
// licenses keeps them all in one LICENSE, one after another. The label is the license
// whose text comes first — that is the license of the module as a whole, and the later
// texts name the parts that are under another license.
func classify(text string) string {
	t := reSpace.ReplaceAllString(text, " ")
	type license struct {
		kind string
		at   int
	}
	var found []license
	add := func(kind string, at int) {
		if at >= 0 {
			found = append(found, license{kind, at})
		}
	}
	if at := strings.Index(t, "Apache License"); at >= 0 && strings.Contains(t, "Version 2.0") {
		add("Apache-2.0", at)
	}
	add("MIT", strings.Index(t, "Permission is hereby granted, free of charge"))
	if m := reISC.FindStringIndex(t); m != nil {
		add("ISC", m[0])
	}
	if at := strings.Index(t, "Redistribution and use in source and binary forms"); at >= 0 {
		// The clauses below occur only in the BSD texts, so they tell the variants apart.
		switch {
		case strings.Contains(t, "advertising materials"):
			add("BSD-4-Clause", at)
		case strings.Contains(t, "endorse or promote"):
			add("BSD-3-Clause", at)
		default:
			add("BSD-2-Clause", at)
		}
	}
	if len(found) == 0 {
		return ""
	}
	slices.SortFunc(found, func(a, b license) int { return a.at - b.at })
	return found[0].kind
}

// readText reads a license file as text: CRLF becomes LF, trailing spaces and newlines go
// away, so the same file gives the same bytes on any system.
func readText(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	return strings.TrimRight(strings.ReplaceAll(string(b), "\r\n", "\n"), " \t\n"), nil
}

// readAll reads license files; the section keeps only their names, no directories.
func readAll(paths []string) ([]licenseText, error) {
	files := make([]licenseText, 0, len(paths))
	for _, p := range paths {
		text, err := readText(p)
		if err != nil {
			return nil, err
		}
		files = append(files, licenseText{Name: filepath.Base(p), Text: text})
	}
	return files, nil
}

// collect is the Go runtime and the standard library, then the modules. A module with no
// license file, or with a text whose kind is not recognised, makes the whole file a
// failure naming every such module: a new dependency has to be looked at by a person, not
// slip into a release.
func collect(mods []module, goroot string) ([]section, error) {
	goFiles, err := readAll([]string{filepath.Join(goroot, "LICENSE"), filepath.Join(goroot, "PATENTS")})
	if err != nil {
		return nil, fmt.Errorf("the Go license: %w", err)
	}
	goKind := classify(goFiles[0].Text)
	if goKind == "" {
		return nil, fmt.Errorf("the Go license in %s: kind not recognised", goroot)
	}
	sections := []section{{
		Title: "Go standard library and runtime",
		Kind:  goKind,
		Note: "The runtime and the standard library are part of the Go distribution\n" +
			"(https://go.dev). The second file is the distribution's additional patent\n" +
			"grant, which covers only the Go code.",
		Files: goFiles,
	}}

	var problems []string
	for _, m := range mods {
		paths, err := licenseFiles(m.Dir)
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s: %v", m.title(), err))
			continue
		}
		if len(paths) == 0 {
			problems = append(problems, fmt.Sprintf("%s: no license file in %s", m.title(), m.Dir))
			continue
		}
		files, err := readAll(paths)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.title(), err)
		}
		kind := classify(files[0].Text)
		if kind == "" {
			problems = append(problems, fmt.Sprintf("%s: license kind not recognised in %s", m.title(), files[0].Name))
			continue
		}
		sections = append(sections, section{Title: m.title(), Kind: kind, Files: files})
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("notices not written, look at these by hand:\n  %s", strings.Join(problems, "\n  "))
	}
	return sections, nil
}

// ownSections are the program's own parts: the shell, MIT, and the dnstt core in core/,
// public domain (CC0). Their texts ship next to the binary as LICENSE and COPYING; they
// are repeated here so that one file answers what the archive is made of.
func ownSections(root string) ([]section, error) {
	shell, err := readAll([]string{filepath.Join(root, "LICENSE")})
	if err != nil {
		return nil, fmt.Errorf("the shell's license: %w", err)
	}
	if kind := classify(shell[0].Text); kind != "MIT" {
		return nil, fmt.Errorf("the shell's LICENSE is not MIT (kind %q)", kind)
	}
	core, err := readAll([]string{filepath.Join(root, "core", "COPYING")})
	if err != nil {
		return nil, fmt.Errorf("the core's license: %w", err)
	}
	return []section{
		{
			Title: "dnstt-cli (the shell)",
			Kind:  "MIT",
			Note:  "The program's own code. The same text is in the archive as LICENSE.",
			Files: shell,
		},
		{
			Title: "dnstt core",
			Kind:  "CC0-1.0",
			Note: "dnstt by David Fifield, public domain dedication; the same text is in\n" +
				"the archive as COPYING.",
			Files: core,
		},
	}, nil
}

// --- text ------------------------------------------------------------------

// render is the text of the file: what it is about, the contents, then the full license
// texts. LF only; nothing about the toolchain or the build machine.
func render(sections []section) string {
	var b strings.Builder
	line := func(s string) { b.WriteString(s + "\n") }
	rule := strings.Repeat("=", 78)

	line("Third-party components of dnstt-cli")
	line("===================================")
	line("")
	line("dnstt-cli is one binary built for windows/amd64 and linux/amd64 from one Go")
	line("module. The list below is the union of what links into it on the two platforms.")
	line("For each component there is the kind of its license and the full text of its")
	line("license files as they are in the component's sources.")
	line("")
	line("The program itself is distributed under the MIT license (LICENSE next to the")
	line("binary); the dnstt core in core/ is public domain, CC0 (COPYING next to the")
	line("binary). Both are repeated at the end, after the third-party components.")
	line("")
	line("Contents:")

	width := 0
	for _, s := range sections {
		width = max(width, len([]rune(s.Title)))
	}
	for _, s := range sections {
		line("  " + s.Title + strings.Repeat(" ", width-len([]rune(s.Title))) + "  " + s.Kind)
	}

	for _, s := range sections {
		line("")
		line("")
		line(rule)
		line(s.Title + " — " + s.Kind)
		line(rule)
		if s.Note != "" {
			line("")
			line(s.Note)
		}
		for _, f := range s.Files {
			line("")
			line("--- " + f.Name + " ---")
			line("")
			line(f.Text)
		}
	}
	return b.String()
}
