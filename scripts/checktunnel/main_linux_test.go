func TestHasUnixSocket(t *testing.T) {
	table := "Num       RefCount Protocol Flags    Type St Inode Path\n" +
		"0000000000000000: 00000002 00000000 00010000 0001 01 4242 @dnstt-cli-tun\n" +
		"0000000000000000: 00000002 00000000 00010000 0001 01 4243 /run/user/1000/bus\n" +
		"0000000000000000: 00000003 00000000 00000000 0001 03 4244\n"
	if !hasUnixSocket([]byte(table), "@dnstt-cli-tun") {
		t.Error("lock not found")
	}
	if hasUnixSocket([]byte(table), "@dnstt-cli") {
		t.Error("found by a part of the name")
	}
}

func TestResolvConfSummary(t *testing.T) {
	conf := "# Generated by resolvconf\nsearch example.com example.org\nnameserver 192.0.2.53\n" +
		"# nameserver 192.0.2.1\nnameserver 2001:db8::53\noptions edns0\n"
	first, servers, search := resolvConfSummary([]byte(conf))
	if first != "# Generated by resolvconf" || strings.Join(servers, ",") != "192.0.2.53,2001:db8::53" || search != 2 {
		t.Errorf("first %q, servers %v, search %d", first, servers, search)
	}
	if first, _, _ := resolvConfSummary([]byte("nameserver 192.0.2.53\n")); first != "" {
		t.Errorf("first line without a comment: %q", first)
	}
}

func TestRoutePrefix(t *testing.T) {
	_, half, _ := net.ParseCIDR("128.0.0.0/1")
	cases := []struct {
		r    netlink.Route
		want string
	}{
		{netlink.Route{Family: unix.AF_INET}, "0.0.0.0/0"},
		{netlink.Route{Family: unix.AF_INET6}, "::/0"},
		{netlink.Route{Family: unix.AF_INET, Dst: half}, "128.0.0.0/1"},
	}
	for _, c := range cases {
		p, ok := routePrefix(c.r)
		if !ok || p.String() != c.want {
			t.Errorf("%v: %s %v, want %s", c.r.Dst, p, ok, c.want)
		}
	}
	if _, ok := routePrefix(netlink.Route{}); ok {
		t.Error("a route without a family and a destination")
	}
}

func TestRules(t *testing.T) {
	std := func(prio, table int) netlink.Rule {
		r := *netlink.NewRule()
		r.Priority, r.Table = prio, table
		return r
	}
	local := std(-1, unix.RT_TABLE_LOCAL) // the kernel does not send priority 0
	if !standardRule(local) || ruleString(local) != "0: from all lookup local" {
		t.Errorf("local: %v %q", standardRule(local), ruleString(local))
	}
	if !standardRule(std(32766, unix.RT_TABLE_MAIN)) || !standardRule(std(32767, unix.RT_TABLE_DEFAULT)) {
		t.Error("main and default are standard")
	}
	marked := std(100, 51820)
	mask := uint32(0xff)
	marked.Mark, marked.Mask, marked.Invert = 0x1075, &mask, true
	if standardRule(marked) {
		t.Error("a rule with a mark is not standard")
	}
	if got := ruleString(marked); got != "100: not from all fwmark 0x1075/0xff lookup 51820" {
		t.Errorf("%q", got)
	}
	_, src, _ := net.ParseCIDR("192.0.2.0/24")
	other := std(32766, unix.RT_TABLE_MAIN)
	other.Src = src
	if standardRule(other) || ruleString(other) != "32766: from 192.0.2.0/24 lookup main" {
		t.Errorf("with a source: %v %q", standardRule(other), ruleString(other))
	}
}

func TestPrintDNS(t *testing.T) {
	dir := t.TempDir()
	etcRoot, runRoot = filepath.Join(dir, "etc"), filepath.Join(dir, "run")
	t.Cleanup(func() { etcRoot, runRoot = "/etc", "/run" })
	write := func(path, s string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(etcRoot, "resolv.conf"), fileMarker+"; previous file: resolv.conf.dnstt-cli-backup\nnameserver 192.0.2.53\n")
	write(filepath.Join(etcRoot, "resolv.conf.dnstt-cli-backup"), "nameserver 192.0.2.1\n")
	write(filepath.Join(runRoot, "resolvconf/interface/NetworkManager"), "nameserver 192.0.2.1\n")
	write(filepath.Join(runRoot, "resolvconf/interface/tun.dnstt-cli"), "nameserver 192.0.2.53\n")

	var b bytes.Buffer
	printDNS(&b, "dnstt-cli")
	out := b.String()
	for _, s := range []string{"regular file", "nameserver: 192.0.2.53", "file written by dnstt-cli",
		"dnstt-cli-backup: present", "NetworkManager, tun.dnstt-cli", "tun.dnstt-cli: nameserver 192.0.2.53"} {
		if !strings.Contains(out, s) {
			t.Errorf("output lacks %q:\n%s", s, out)
		}
	}
}

// TestRunOffline runs the snapshot on the real system without the network: all sections
// are there, the network ones are not. Without root rights the nftables section has an
// error, which is fine.
func TestRunOffline(t *testing.T) {
	var b bytes.Buffer
	run(&b, options{label: "test", name: "dnstt-cli-test-absent", offline: true})
	out := b.String()
	for _, s := range []string{"— test ===", "-- dnstt-cli processes", "lock @dnstt-cli-tun", "-- Interfaces",
		`no tunnel adapter "dnstt-cli-test-absent"`, "-- Routes /0 and /1", "-- Routing rules",
		"-- Interface for the core's sockets", "-- nftables", "-- System DNS", "dnstt-cli method",
		"-- Reverse-path filter"} {
		if !strings.Contains(out, s) {
			t.Errorf("output lacks %q:\n%s", s, out)
		}
	}
	for _, s := range []string{"External address", "Resolver"} {
		if strings.Contains(out, s) {
			t.Errorf("with offline the output has %q", s)
		}
	}
	t.Log("\n" + out)
}
