func TestStatusUID(t *testing.T) {
	status := "Name:\ttt\nUmask:\t0022\nUid:\t1000\t0\t0\t0\nGid:\t1000\t0\t0\t0\n"
	if got := statusUID([]byte(status)); got != "0" {
		t.Errorf("uid %q, want the effective 0", got)
	}
	if got := statusUID([]byte("Name:\ttt\n")); got != "?" {
		t.Errorf("no Uid line: %q", got)
	}
}

