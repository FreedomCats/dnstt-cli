package linuxsys

import (
	"net/netip"
	"path/filepath"
	"slices"
	"testing"
)

func TestNetworkDNS(t *testing.T) {
	for _, tc := range []struct {
		name     string
		conf     string // /etc/resolv.conf
		backup   string // its copy by dnstt-cli; "" — none
		resolved string // /run/systemd/resolve/resolv.conf; "" — none
		want     []string
		err      bool
	}{
		{name: "plain file",
			conf: "# Generated by NetworkManager\nsearch home\nnameserver 192.0.2.53\nnameserver 2001:db8::53\nnameserver 192.0.2.53\n",
			want: []string{"192.0.2.53", "2001:db8::53"}},
		{name: "local cache left out",
			conf: "nameserver 127.0.0.1\nnameserver ::1\nnameserver 198.51.100.53\n",
			want: []string{"198.51.100.53"}},
		{name: "systemd-resolved stub",
			conf:     "nameserver 127.0.0.53\noptions edns0 trust-ad\n",
			resolved: "nameserver 192.0.2.53\nnameserver 192.0.2.54\nsearch .\n",
			want:     []string{"192.0.2.53", "192.0.2.54"}},
		{name: "stub without the service", conf: "nameserver 127.0.0.53\n", err: true},
		{name: "our own file",
			conf:   fileMarker + "\nnameserver 198.51.100.1\n",
			backup: "nameserver 203.0.113.53\n",
			want:   []string{"203.0.113.53"}},
		{name: "nothing", conf: "# empty\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, etc := fakeRoots(t)
			run := t.TempDir()
			old := runRoot
			runRoot = run
			t.Cleanup(func() { runRoot = old })
			writeFile(t, filepath.Join(etc, "resolv.conf"), tc.conf)
			if tc.backup != "" {
				writeFile(t, filepath.Join(etc, "resolv.conf"+backupSuffix), tc.backup)
			}
			if tc.resolved != "" {
				writeFile(t, filepath.Join(run, "systemd/resolve/resolv.conf"), tc.resolved)
			}
			got, err := NetworkDNS()
			if tc.err {
				if err == nil {
					t.Fatalf("no error, got %v", got)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			var want []netip.Addr
			for _, s := range tc.want {
				want = append(want, netip.MustParseAddr(s))
			}
			if !slices.Equal(got, want) {
				t.Errorf("got %v, want %v", got, want)
			}
		})
	}
}
