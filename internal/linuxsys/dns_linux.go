// Tunnel DNS in the system. On Windows DNS is a property of the adapter
// (winsys.SetAdapterDNS); on Linux there is no single way: whoever manages
// /etc/resolv.conf sets the system DNS. dnstt-cli finds out who from the file itself.
//
//   - systemd-resolved: the file points into /run/systemd/resolve or names its stub
//     127.0.0.53. DNS is set on the dnstt-cli link over D-Bus with the routing domain
//     "~." and goes away together with the link; no cleanup is needed.
//   - resolvconf: the file points into /run/resolvconf (Debian) or was written by it
//     (openresolv writes an ordinary file with the header "Generated by resolvconf").
//     The record is tun.<adapter>: the tun prefix puts it first (interface-order).
//     Debian resolvconf has no exclusive mode, and the network's servers stay in the
//     file after ours; DNS protection (DNSGuard) drops queries to them. openresolv runs
//     with -m 0 -x, as wg-quick does: only ours are in the file.
//   - Overwrite: an ordinary file nobody manages (a container): a copy goes to
//     resolv.conf.dnstt-cli-backup, our own file with a marker is written, and the
//     copy is put back on exit.
//
// After dnstt-cli crashes (kill -9) the resolvconf record and the overwritten file
// stay; Recover of the next run removes them.

// DNSMethod is the way dnstt-cli sets the system DNS.
type DNSMethod int

const (
	DNSResolved DNSMethod = iota + 1
	DNSResolvconfDebian
	DNSOpenresolv
	DNSFile
)

func (m DNSMethod) String() string {
	switch m {
	case DNSResolved:
		return "systemd-resolved"
	case DNSResolvconfDebian:
		return "resolvconf (Debian)"
	case DNSOpenresolv:
		return "openresolv"
	case DNSFile:
		return "overwrite /etc/resolv.conf"
	default:
		return fmt.Sprintf("DNSMethod(%d)", int(m))
	}
}

// runRoot is the root of /run; tests replace it (as etcRoot).
var runRoot = "/run"

// resolvedStub is the address of the systemd-resolved stub in resolv.conf.
const resolvedStub = "127.0.0.53"

// resolvconfHeader is the header of the file openresolv writes.
const resolvconfHeader = "# Generated by resolvconf"

// fileMarker starts the first line of a resolv.conf written by dnstt-cli: by it Recover
// and Revert tell our own file from one written by someone else afterwards.
// scripts/checktunnel has the same constant; the two must stay equal.
const fileMarker = "# " + app.Name + ": tunnel DNS"

// backupSuffix names the copy of the previous resolv.conf next to it.
const backupSuffix = "." + app.Name + "-backup"

// SystemDNS is the tunnel DNS in the system for the adapter named name.
// Not safe for concurrent use: one goroutine of the adapter calls it.
type SystemDNS struct {
	method DNSMethod
	name   string
	// resolvconf is the path to the resolvconf program (Debian and openresolv).
	resolvconf string
	// warning is what makes the method unreliable (Warning).
	warning string
	// applied means Set was called and Revert has something to remove: it is marked
	// before the calls, so a half-done setup is removed too (SetLinkDNS succeeded,
	// SetLinkDomains did not).
	applied bool
}

// DetectSystemDNS finds out who manages /etc/resolv.conf and the way dnstt-cli will set
// the tunnel DNS for adapter name. It changes nothing. A link to an unknown generator is
// an error: overwriting the file would break resolv.conf for its owner until dnstt-cli
// exits.
func DetectSystemDNS(name string) (*SystemDNS, error) {
	method, resolvconf, err := detectDNSMethod()
	if err != nil {
		return nil, err
	}
	s := &SystemDNS{method: method, name: name, resolvconf: resolvconf}
	if method == DNSFile {
		if b, err := os.ReadFile(resolvConfPath()); err == nil {
			if gen := fileGenerator(b); gen != "" {
				s.warning = fmt.Sprintf("resolv.conf is written by %s: if it rewrites the file (network change, DHCP "+
					"renewal), the tunnel DNS is lost until dnstt-cli reconnects", gen)
			}
		}
	}
	return s, nil
}

// fileGenerator returns who wrote resolv.conf, by the header "# Generated by …"; ""
// means unknown or docker (it leaves the file alone once edited).
func fileGenerator(conf []byte) string {
	line := firstLine(string(conf))
	gen, ok := strings.CutPrefix(line, "# Generated by ")
	if !ok || strings.HasPrefix(gen, "Docker") {
		return ""
	}
	return strings.TrimRight(gen, ". ")
}

func detectDNSMethod() (DNSMethod, string, error) {
	path := resolvConfPath()
	fi, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return DNSFile, "", nil
	}
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf: %w", err)
	}

	if fi.Mode()&fs.ModeSymlink == 0 {
		b, err := os.ReadFile(path)
		if err != nil {
			return 0, "", fmt.Errorf("resolv.conf: %w", err)
		}
		switch {
		case hasNameserver(b, resolvedStub):
			// A copy of the stub file without a link is systemd-resolved too.
			return resolvedMethod()
		case bytes.Contains(b, []byte(resolvconfHeader)):
			return resolvconfMethod()
		}
		return DNSFile, "", nil
	}

	target, err := filepath.EvalSymlinks(path)
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf is a link that leads nowhere: %w", err)
	}
	run := runRoot
	if r, err := filepath.EvalSymlinks(runRoot); err == nil {
		run = r
	}
	switch {
	case under(target, filepath.Join(run, "systemd/resolve")):
		return resolvedMethod()
	case under(target, filepath.Join(run, "resolvconf")):
		return resolvconfMethod()
	default:
		return 0, "", fmt.Errorf("/etc/resolv.conf is a link to %s: dnstt-cli does not know this generator "+
			"(it handles systemd-resolved, resolvconf and an ordinary file) and cannot set the tunnel DNS", target)
	}
}

// resolvedMethod picks systemd-resolved if the service answers over D-Bus.
func resolvedMethod() (DNSMethod, string, error) {
	bus, err := dialResolved()
	if err == nil {
		err = bus.call(context.Background(), "org.freedesktop.DBus.Peer.Ping")
		bus.close()
	}
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf points to systemd-resolved, but the service does not answer: %w", err)
	}
	return DNSResolved, "", nil
}

// resolvconfMethod picks Debian resolvconf or openresolv: --version tells them apart.
func resolvconfMethod() (DNSMethod, string, error) {
	prog, err := findResolvconf()
	if err != nil {
		return 0, "", err
	}
	out, err := runCommand(nil, prog, "--version")
	if err != nil {
		return 0, "", fmt.Errorf("resolvconf --version: %w", err)
	}
	switch v := string(out); {
	case strings.Contains(v, "Debian resolvconf"):
		return DNSResolvconfDebian, prog, nil
	case strings.Contains(v, "openresolv"):
		return DNSOpenresolv, prog, nil
	default:
		return 0, "", fmt.Errorf("resolv.conf is managed by resolvconf, but %s is unknown (%q)", prog, firstLine(v))
	}
}

// findResolvconf finds the resolvconf program: under sudo PATH usually includes sbin,
// but not always.
func findResolvconf() (string, error) {
	for _, p := range resolvconfPaths {
		if fi, err := os.Stat(p); err == nil && !fi.IsDir() {
			return p, nil
		}
	}
	if p, err := exec.LookPath("resolvconf"); err == nil {
		return p, nil
	}
	return "", errors.New("resolv.conf is managed by resolvconf, but there is no resolvconf program")
}

// resolvconfPaths is where to look for resolvconf before PATH; tests replace it.
var resolvconfPaths = []string{"/usr/sbin/resolvconf", "/sbin/resolvconf"}

// Applied reports whether Set was called after the last Revert: what was set, even
// partly, has not been removed yet.
func (s *SystemDNS) Applied() bool { return s.applied }

// Warning returns what makes the chosen method unreliable; "" means nothing.
func (s *SystemDNS) Warning() string { return s.warning }

// Method returns the chosen method.
func (s *SystemDNS) Method() DNSMethod { return s.method }

// String returns the method for an output line.
func (s *SystemDNS) String() string {
	switch s.method {
	case DNSResolvconfDebian, DNSOpenresolv:
		return fmt.Sprintf("%s, record %s", s.method, s.record())
	case DNSResolved:
		return fmt.Sprintf("%s, link %s", s.method, s.name)
	case DNSFile:
		return fmt.Sprintf("%s, previous one in %s", s.method, backupPath())
	}
	return s.method.String()
}

// record returns the name of the resolvconf record.
func (s *SystemDNS) record() string { return "tun." + s.name }

// Recover removes what a crashed previous run left behind: the resolvconf record and
// the overwritten resolv.conf. Call it before Set and only when there can be no second
// dnstt-cli on the machine (after the adapter lock); otherwise the DNS of the running
// one would be removed. Returns what was removed; "" means nothing.
func (s *SystemDNS) Recover() (string, error) {
	switch s.method {
	case DNSResolvconfDebian, DNSOpenresolv:
		if !s.recordExists() {
			return "", nil
		}
		if err := s.deleteRecord(); err != nil {
			return "", fmt.Errorf("record %s of the previous run: %w", s.record(), err)
		}
		return fmt.Sprintf("record %s of the previous dnstt-cli run removed", s.record()), nil
	case DNSFile:
		return restoreFile()
	}
	// systemd-resolved: the link settings went away together with the link.
	return "", nil
}

// recordExists reports whether the resolvconf record exists (Debian keeps records in
// interface, openresolv in interfaces).
func (s *SystemDNS) recordExists() bool {
	for _, dir := range []string{"interface", "interfaces"} {
		if _, err := os.Stat(filepath.Join(runRoot, "resolvconf", dir, s.record())); err == nil {
			return true
		}
	}
	return false
}

// Set makes servers the system DNS; calling it again replaces the previous ones. index
// is the interface index of the adapter (for systemd-resolved). An empty servers
// removes what was set: no DNS was given, the system DNS stays.
//
// After a failure Revert still removes whatever got set: every method harmlessly
// removes what was not done too (RevertLink, resolvconf -d, restoring a copy that does
// not exist).
func (s *SystemDNS) Set(index int, servers []netip.Addr) error {
	if len(servers) == 0 {
		return s.Revert(index)
	}
	s.applied = true
	var err error
	switch s.method {
	case DNSResolved:
		err = setResolved(index, servers)
	case DNSResolvconfDebian:
		_, err = runCommand(resolvconfInput(servers), s.resolvconf, "-a", s.record())
	case DNSOpenresolv:
		_, err = runCommand(resolvconfInput(servers), s.resolvconf, "-a", s.record(), "-m", "0", "-x")
	case DNSFile:
		err = writeResolvConf(servers)
	default:
		err = fmt.Errorf("unknown method %v", s.method)
	}
	if err != nil {
		return fmt.Errorf("system DNS (%s): %w", s.method, err)
	}
	return nil
}

// Revert removes what Set installed; without Set it does nothing.
// Calling it again is harmless.
func (s *SystemDNS) Revert(index int) error {
	if !s.applied {
		return nil
	}
	var err error
	switch s.method {
	case DNSResolved:
		err = revertResolved(index)
	case DNSResolvconfDebian, DNSOpenresolv:
		err = s.deleteRecord()
	case DNSFile:
		_, err = restoreFile()
	}
	if err != nil {
		return fmt.Errorf("system DNS (%s): %w", s.method, err)
	}
	s.applied = false
	return nil
}

func (s *SystemDNS) deleteRecord() error {
	args := []string{"-d", s.record()}
	if s.method == DNSOpenresolv {
		// Without -f openresolv complains about a missing record; Debian does not know
		// -f and silently skips a missing record.
		args = []string{"-f", "-d", s.record()}
	}
	_, err := runCommand(nil, s.resolvconf, args...)
	return err
}

// resolvconfInput returns the resolvconf record: servers only. search and options come
// from other records.
func resolvconfInput(servers []netip.Addr) []byte {
	var b bytes.Buffer
	for _, a := range servers {
		fmt.Fprintf(&b, "nameserver %s\n", a.Unmap())
	}
	return b.Bytes()
}

// runCommand runs a program and returns its output; the error includes the program's
// stderr.
var runCommand = func(stdin []byte, prog string, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), commandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, prog, args...)
	if stdin != nil {
		cmd.Stdin = bytes.NewReader(stdin)
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		if msg := strings.TrimSpace(stderr.String()); msg != "" {
			return out, fmt.Errorf("%s %s: %w: %s", filepath.Base(prog), strings.Join(args, " "), err, msg)
		}
		return out, fmt.Errorf("%s %s: %w", filepath.Base(prog), strings.Join(args, " "), err)
	}
	return out, nil
}

// commandTimeout: resolvconf waits up to 10 s for its lock.
const commandTimeout = 20 * time.Second

// ──────────────────────────── systemd-resolved ────────────────────────────

// resolvedBus makes the systemd-resolved calls; an interface for the sake of tests.
type resolvedBus interface {
	// call calls an org.freedesktop.resolve1 method on /org/freedesktop/resolve1; a name
	// without an interface is a Manager method.
	call(ctx context.Context, method string, args ...any) error
	close()
}

// dialResolved connects to the system bus; tests replace it.
var dialResolved = func() (resolvedBus, error) {
	conn, err := dbus.ConnectSystemBus()
	if err != nil {
		return nil, fmt.Errorf("D-Bus system bus: %w", err)
	}
	return dbusResolved{conn: conn}, nil
}

type dbusResolved struct{ conn *dbus.Conn }

func (b dbusResolved) call(ctx context.Context, method string, args ...any) error {
	if !strings.Contains(method, ".") {
		method = "org.freedesktop.resolve1.Manager." + method
	}
	obj := b.conn.Object("org.freedesktop.resolve1", "/org/freedesktop/resolve1")
	return obj.CallWithContext(ctx, method, 0, args...).Err
}

func (b dbusResolved) close() { b.conn.Close() }

// resolvedTimeout is the timeout of one systemd-resolved call.
const resolvedTimeout = 10 * time.Second

// resolvedAddr is an address in SetLinkDNS: a(iay).
type resolvedAddr struct {
	Family  int32
	Address []byte
}

// resolvedDomain is a domain in SetLinkDomains: a(sb).
type resolvedDomain struct {
	Domain      string
	RoutingOnly bool
}

// setResolved sets on the link the DNS servers, the routing domain "~." (all names go
// here, except more specific domains of other links) and DefaultRoute.
func setResolved(index int, servers []netip.Addr) error {
	addrs := make([]resolvedAddr, 0, len(servers))
	for _, a := range servers {
		a = a.Unmap()
		family := int32(unix.AF_INET)
		if a.Is6() {
			family = unix.AF_INET6
		}
		addrs = append(addrs, resolvedAddr{Family: family, Address: a.AsSlice()})
	}
	return withResolved(func(ctx context.Context, bus resolvedBus) error {
		if err := bus.call(ctx, "SetLinkDNS", int32(index), addrs); err != nil {
			return fmt.Errorf("SetLinkDNS: %w", err)
		}
		if err := bus.call(ctx, "SetLinkDomains", int32(index), []resolvedDomain{{".", true}}); err != nil {
			return fmt.Errorf("SetLinkDomains: %w", err)
		}
		// SetLinkDefaultRoute exists since systemd 240; for older ones "~." is enough.
		if err := bus.call(ctx, "SetLinkDefaultRoute", int32(index), true); err != nil && !dbusErrorIs(err, "org.freedesktop.DBus.Error.UnknownMethod") {
			return fmt.Errorf("SetLinkDefaultRoute: %w", err)
		}
		return nil
	})
}

// revertResolved removes the link settings. If the link is already gone, there is
// nothing to remove.
func revertResolved(index int) error {
	return withResolved(func(ctx context.Context, bus resolvedBus) error {
		err := bus.call(ctx, "RevertLink", int32(index))
		if err != nil && !dbusErrorIs(err, "org.freedesktop.resolve1.NoSuchLink") {
			return fmt.Errorf("RevertLink: %w", err)
		}
		return nil
	})
}

func withResolved(f func(context.Context, resolvedBus) error) error {
	bus, err := dialResolved()
	if err != nil {
		return err
	}
	defer bus.close()
	ctx, cancel := context.WithTimeout(context.Background(), resolvedTimeout)
	defer cancel()
	return f(ctx, bus)
}

func dbusErrorIs(err error, name string) bool {
	var derr dbus.Error
	if errors.As(err, &derr) {
		return derr.Name == name
	}
	var perr *dbus.Error
	return errors.As(err, &perr) && perr.Name == name
}

// ──────────────────────────── overwrite ────────────────────────────

func resolvConfPath() string { return filepath.Join(etcRoot, "resolv.conf") }

func backupPath() string { return resolvConfPath() + backupSuffix }

// writeResolvConf writes our own resolv.conf; if there is no copy yet, the previous one
// goes into the copy first. If a copy exists, the file is already ours (Set again).
func writeResolvConf(servers []netip.Addr) error {
	path := resolvConfPath()
	old, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if _, err := os.Stat(backupPath()); errors.Is(err, fs.ErrNotExist) {
		if bytes.HasPrefix(old, []byte(fileMarker)) {
			// Our own file without a copy: someone deleted the copy; the previous file
			// cannot be restored, but our own must not be copied as the previous one.
			return fmt.Errorf("%s was written by dnstt-cli, but there is no copy of the previous one (%s)", path, backupPath())
		}
		if err := replaceFile(backupPath(), old); err != nil {
			return fmt.Errorf("copy of resolv.conf: %w", err)
		}
	} else if err != nil {
		return err
	}
	return replaceFile(path, fileContent(servers, old))
}

// fileContent returns our own resolv.conf: the marker, the tunnel servers and, from the
// previous file, search, domain and options (short names and resolver settings stay the
// same).
func fileContent(servers []netip.Addr, old []byte) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s; previous file is %s, dnstt-cli will restore it on exit\n", fileMarker, filepath.Base(backupPath()))
	for _, a := range servers {
		fmt.Fprintf(&b, "nameserver %s\n", a.Unmap())
	}
	for _, line := range strings.Split(string(old), "\n") {
		f := strings.Fields(line)
		if len(f) > 0 && (f[0] == "search" || f[0] == "domain" || f[0] == "options") {
			b.WriteString(strings.TrimSpace(line) + "\n")
		}
	}
	return b.Bytes()
}

// restoreFile restores the previous resolv.conf from the copy. If the file is no longer
// ours, someone wrote it afterwards (DHCP, NetworkManager): it stays, and the copy is
// deleted. Returns what was done; "" means there was no copy.
func restoreFile() (string, error) {
	backup, err := os.ReadFile(backupPath())
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	if err != nil {
		return "", fmt.Errorf("copy of resolv.conf: %w", err)
	}
	cur, err := os.ReadFile(resolvConfPath())
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}
	done := "previous resolv.conf restored from " + backupPath()
	if bytes.HasPrefix(cur, []byte(fileMarker)) {
		if err := replaceFile(resolvConfPath(), backup); err != nil {
			return "", fmt.Errorf("restoring resolv.conf: %w", err)
		}
	} else {
		done = "resolv.conf was rewritten by someone else after dnstt-cli; it stays, copy " + backupPath() + " deleted"
	}
	if err := os.Remove(backupPath()); err != nil {
		return "", err
	}
	return done, nil
}

// replaceFile replaces a file as a whole: a new one next to it and a rename, so that a
// reader never sees half of it. In a container resolv.conf is mounted separately, and a
// rename over a mount point gives EBUSY: then it is written in place.
// The permissions of the previous file are kept.
func replaceFile(path string, data []byte) error {
	mode := fs.FileMode(0o644)
	if fi, err := os.Stat(path); err == nil {
		mode = fi.Mode().Perm()
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+"."+app.Name+"-*")
	if err != nil {
		return err
	}
	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(mode)
	}
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Rename(tmp.Name(), path)
		if err == nil {
			return nil
		}
	}
	os.Remove(tmp.Name())
	if !errors.Is(err, syscall.EBUSY) {
		return err
	}
	return os.WriteFile(path, data, mode)
}

// ──────────────────────────── misc ────────────────────────────

// hasNameserver reports whether resolv.conf has the line nameserver addr.
func hasNameserver(conf []byte, addr string) bool {
	for _, line := range strings.Split(string(conf), "\n") {
		f := strings.Fields(line)
		if len(f) >= 2 && f[0] == "nameserver" && f[1] == addr {
			return true
		}
	}
	return false
}

// under reports whether path lies inside dir.
func under(path, dir string) bool {
	rel, err := filepath.Rel(dir, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, "../")
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(strings.TrimSpace(s), "\n")
	return line
}
