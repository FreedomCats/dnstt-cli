// fakeDNSRoots sets up fake /etc and /run and turns off the search for resolvconf.
func fakeDNSRoots(t *testing.T) (etc, run string) {
	t.Helper()
	_, etc = fakeRoots(t)
	run = t.TempDir()
	oldRun, oldPaths := runRoot, resolvconfPaths
	runRoot, resolvconfPaths = run, nil
	t.Cleanup(func() { runRoot, resolvconfPaths = oldRun, oldPaths })
	return etc, run
}

// fakeCommands replaces running programs: version is the answer to --version, calls
// are recorded in calls.
type fakeCommands struct {
	version string
	calls   []string
	stdins  []string
}

func stubCommands(t *testing.T, version string) *fakeCommands {
	t.Helper()
	f := &fakeCommands{version: version}
	old := runCommand
	runCommand = func(stdin []byte, prog string, args ...string) ([]byte, error) {
		if slices.Equal(args, []string{"--version"}) {
			return []byte(f.version), nil
		}
		f.calls = append(f.calls, filepath.Base(prog)+" "+strings.Join(args, " "))
		f.stdins = append(f.stdins, string(stdin))
		return nil, nil
	}
	t.Cleanup(func() { runCommand = old })
	return f
}

// fakeResolvconf puts a resolvconf program where the search will find it.
func fakeResolvconf(t *testing.T) string {
	t.Helper()
	prog := filepath.Join(t.TempDir(), "resolvconf")
	writeFile(t, prog, "#!/bin/sh\n")
	resolvconfPaths = []string{prog}
	return prog
}

func symlink(t *testing.T, target, link string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(link), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}
}

// fakeBus is systemd-resolved on a fake bus.
type fakeBus struct {
	calls  []string
	args   [][]any
	errs   map[string]error
	closed int
}

func (b *fakeBus) call(_ context.Context, method string, args ...any) error {
	b.calls = append(b.calls, method)
	b.args = append(b.args, args)
	return b.errs[method]
}

func (b *fakeBus) close() { b.closed++ }

func stubBus(t *testing.T, bus *fakeBus, dialErr error) {
	t.Helper()
	old := dialResolved
	dialResolved = func() (resolvedBus, error) {
		if dialErr != nil {
			return nil, dialErr
		}
		return bus, nil
	}
	t.Cleanup(func() { dialResolved = old })
}

