func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func exists(path string) bool {
	_, err := os.Lstat(path)
	return err == nil
}

// Overwrite: a copy of the previous file, our own file with search and options of the
// previous one, a repeated Set leaves the copy alone, Revert restores the previous one.
func TestSystemDNSFile(t *testing.T) {
	etc, _ := fakeDNSRoots(t)
	path := filepath.Join(etc, "resolv.conf")
	orig := "# from DHCP\nnameserver 192.0.2.1\nsearch example.net\noptions ndots:2\n"
	writeFile(t, path, orig)
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}

	dns, err := DetectSystemDNS("dnstt-cli")
	if err != nil {
		t.Fatal(err)
	}
	if done, err := dns.Recover(); err != nil || done != "" {
		t.Fatalf("Recover on a clean system: %q, %v", done, err)
	}
	if err := dns.Revert(1); err != nil {
		t.Fatalf("Revert before Set: %v", err)
	}
	if got := readFile(t, path); got != orig {
		t.Fatalf("Revert before Set touched the file: %q", got)
	}

	if err := dns.Set(1, testServers); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, path)
	want := fileMarker + "; previous file is resolv.conf.dnstt-cli-backup, dnstt-cli will restore it on exit\n" +
		"nameserver 192.0.2.53\nnameserver 2001:db8::53\nsearch example.net\noptions ndots:2\n"
	if got != want {
		t.Errorf("own file:\n%s\nwant:\n%s", got, want)
	}
	if b := readFile(t, path+".dnstt-cli-backup"); b != orig {
		t.Errorf("copy: %q", b)
	}
	if fi, _ := os.Stat(path); fi.Mode().Perm() != 0o640 {
		t.Errorf("permissions %v, want 0640", fi.Mode().Perm())
	}
	if !dns.Applied() {
		t.Error("Applied after Set = false")
	}

	// A new DNS server means a new file, the same copy.
	if err := dns.Set(1, testServers[:1]); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, path); !strings.Contains(got, "nameserver 192.0.2.53\nsearch") {
		t.Errorf("after a repeated Set:\n%s", got)
	}
	if b := readFile(t, path+".dnstt-cli-backup"); b != orig {
		t.Errorf("repeated Set rewrote the copy: %q", b)
	}

	if err := dns.Revert(1); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, path); got != orig {
		t.Errorf("after Revert: %q", got)
	}
	if exists(path + ".dnstt-cli-backup") {
		t.Error("copy left after Revert")
	}
	if err := dns.Revert(1); err != nil {
		t.Errorf("repeated Revert: %v", err)
	}
	entries, _ := os.ReadDir(etc)
	if len(entries) != 1 {
		t.Errorf("extra files in /etc: %v", entries)
	}
}

