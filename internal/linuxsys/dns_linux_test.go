// An ordinary file written by another program means an overwrite with a warning; a
// docker file, without one.
func TestSystemDNSFileWarning(t *testing.T) {
	for _, tc := range []struct{ conf, want string }{
		{"# Generated by NetworkManager\nnameserver 192.0.2.1\n", "resolv.conf is written by NetworkManager:"},
		{"# Generated by Docker Engine.\nnameserver 192.0.2.1\n", ""},
		{"nameserver 192.0.2.1\n", ""},
	} {
		etc, _ := fakeDNSRoots(t)
		writeFile(t, filepath.Join(etc, "resolv.conf"), tc.conf)
		dns, err := DetectSystemDNS("dnstt-cli")
		if err != nil {
			t.Fatal(err)
		}
		if dns.Method() != DNSFile || !strings.HasPrefix(dns.Warning(), tc.want) || (tc.want == "") != (dns.Warning() == "") {
			t.Errorf("%q: method %v, warning %q", tc.conf, dns.Method(), dns.Warning())
		}
	}
}
