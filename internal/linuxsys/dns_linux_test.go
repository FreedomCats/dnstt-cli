// Leftovers of a crashed run: our own file and a copy, the previous one is restored; a
// copy with a foreign file is deleted.
func TestSystemDNSFileRecover(t *testing.T) {
	etc, _ := fakeDNSRoots(t)
	path := filepath.Join(etc, "resolv.conf")
	orig := "nameserver 192.0.2.1\n"
	writeFile(t, path, orig)
	crashed, _ := DetectSystemDNS("dnstt-cli")
	if err := crashed.Set(1, testServers); err != nil {
		t.Fatal(err)
	}
	// kill -9: there was no Revert.

	dns, err := DetectSystemDNS("dnstt-cli")
	if err != nil {
		t.Fatal(err)
	}
	done, err := dns.Recover()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(done, "restored") {
		t.Errorf("Recover: %q", done)
	}
	if got := readFile(t, path); got != orig || exists(path+".dnstt-cli-backup") {
		t.Errorf("after Recover: %q, copy present: %v", got, exists(path+".dnstt-cli-backup"))
	}

	writeFile(t, path+".dnstt-cli-backup", "nameserver 203.0.113.1\n")
	done, err = dns.Recover()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(done, "rewritten by someone else") || readFile(t, path) != orig || exists(path+".dnstt-cli-backup") {
		t.Errorf("Recover with a foreign file: %q, file %q", done, readFile(t, path))
	}
}

